def plot_bar_counts(series, title, xlabel, ylabel):
    counts = series.value_counts()
    plt.figure()
    counts.plot(kind="bar")
    plt.title(title)
    plt.xlabel(xlabel)
    plt.ylabel(ylabel)
    plt.tight_layout()
    plt.show()

def plot_hist(values, title, xlabel, bins=40):
    plt.figure()
    plt.hist(values, bins=bins)
    plt.title(title)
    plt.xlabel(xlabel)
    plt.ylabel("Frequency")
    plt.tight_layout()
    plt.show()

def plot_confusion(cm, class_names, title):
    plt.figure(figsize=(7, 6))
    plt.imshow(cm, interpolation="nearest")
    plt.title(title)
    plt.colorbar()
    tick_marks = np.arange(len(class_names))
    plt.xticks(tick_marks, class_names, rotation=45, ha="right")
    plt.yticks(tick_marks, class_names)
    plt.xlabel("Predicted")
    plt.ylabel("Actual")

    # annotate
    thresh = cm.max() * 0.6 if cm.max() > 0 else 0.0
    for i in range(cm.shape[0]):
        for j in range(cm.shape[1]):
            val = cm[i, j]
            plt.text(j, i, str(val), ha="center", va="center",
                     color="white" if val > thresh else "black")

    plt.tight_layout()
    plt.show()

def plot_model_comparison(df_metrics, title):
    # df_metrics: columns -> model, accuracy, f1_weighted, train_time_sec
    models = df_metrics["model"].tolist()
    acc = df_metrics["accuracy"].tolist()
    f1w = df_metrics["f1_weighted"].tolist()

    x = np.arange(len(models))
    w = 0.35

    plt.figure(figsize=(8, 4.5))
    plt.bar(x - w/2, acc, width=w, label="Accuracy")
    plt.bar(x + w/2, f1w, width=w, label="F1 (weighted)")
    plt.xticks(x, models, rotation=15)
    plt.ylim(0, 1.0)
    plt.title(title)
    plt.ylabel("Score")
    plt.legend()
    plt.tight_layout()
    plt.show()


