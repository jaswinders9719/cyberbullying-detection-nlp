def ensure_nltk():
    nltk.download("stopwords", quiet=True)
    nltk.download("wordnet", quiet=True)
    nltk.download("omw-1.4", quiet=True)

_URL = re.compile(r"http\S+|www\.\S+")
_MENTION = re.compile(r"@\w+")
_HASH = re.compile(r"#")
_NONALPHA = re.compile(r"[^a-z\s]+")

def make_cleaner():
    sw = set(stopwords.words("english"))
    lem = WordNetLemmatizer()

    def clean(text):
        if text is None:
            return ""
        t = str(text).lower()
        t = _URL.sub(" ", t)
        t = _MENTION.sub(" ", t)
        t = _HASH.sub(" ", t)
        t = _NONALPHA.sub(" ", t)
        t = re.sub(r"\s+", " ", t).strip()
        if not t:
            return ""
        toks = [lem.lemmatize(w) for w in t.split() if w not in sw]
        return " ".join(toks)

    return clean

def safe_text(s, empty_token="[EMPTY]", max_chars=2000):
    if s is None:
        return empty_token
    t = str(s).strip()
    if not t:
        t = empty_token
    if len(t) > max_chars:
        t = t[:max_chars]
    return t


