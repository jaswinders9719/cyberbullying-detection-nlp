def bert_predict(texts):
    texts = safe_texts(texts)
    enc = tokenizer(
        list(texts),
        padding=True,
        truncation=True,
        max_length=64,
        return_tensors="pt"
    ).to(device)

    with torch.no_grad():
        outputs = model(**enc)

    probs = outputs.logits.softmax(dim=1).detach().cpu().numpy()
    if probs.ndim == 1:
        probs = probs.reshape(1, -1)
    return probs

