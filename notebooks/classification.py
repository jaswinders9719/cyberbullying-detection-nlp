# safe input helper: replace empty/whitespace, truncate very long texts
def safe_texts(items, max_chars=1500, empty_token="[EMPTY]"):
    texts = [str(t) for t in items]
    out = []
    for t in texts:
        t = t.strip()
        if not t:
            t = empty_token
        if len(t) > max_chars:
            t = t[:max_chars]
        out.append(t)
    return out

