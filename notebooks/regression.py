# 2) Containers for results
# -----------------------------

reg_rows = []


# -----------------------------
# 4) Multi-output regression evaluation (ALL OUTPUTS)
# -----------------------------
target_names = list(y_train_reg.columns)  # keeps your original column names

for model_name, base_model in reg_pool.items():
    wrapper = MultiOutputRegressor(base_model)
    wrapper.fit(X_train_reg, y_train_reg)

    pred = wrapper.predict(X_test_reg)

    # arrays of length = num_outputs
    mse_vals = mean_squared_error(y_test_reg, pred, multioutput="raw_values")
    r2_vals = r2_score(y_test_reg, pred, multioutput="raw_values")

    row = {"Model": model_name}

    # expand into columns dynamically
    for j, target in enumerate(target_names):
        row[f"{target} MSE"] = round(float(mse_vals[j]), 4)
        row[f"{target} R2"] = round(float(r2_vals[j]), 4)

    reg_rows.append(row)

df = pd.DataFrame(reg_rows).round(4)

mse_cols = ["Model"] + [c for c in df.columns if "MSE" in c]
