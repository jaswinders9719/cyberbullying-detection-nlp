def clean_text(text):
    text = str(text).lower()
    text = re.sub(r"@\w+|\#", "", text)          # mentions + hashtag symbol
    text = re.sub(r"https?:\/\/\S+", "", text)   # URLs
    text = text.translate(str.maketrans("", "", string.punctuation))
    text = re.sub(r"\s+", " ", text).strip()
    return text

df_final["text"] = df_final["text"].apply(clean_text)

